#!/usr/bin/env python3
"""Regenerate src/presets_embed.cpp from assets/presets/<App name>/<TITLE ID>/<n>.png (preset icons).
Run from the repository root:  python3 tools/embed_presets.py"""
import os, re

root = "assets/presets"
items = []
for app in sorted(os.listdir(root)):
    for tid in sorted(os.listdir(os.path.join(root, app))):
        d = os.path.join(root, app, tid)
        if not os.path.isdir(d) or not re.fullmatch(r"[A-Z]{4}\d{5}", tid): continue
        names = sorted((n for n in os.listdir(d) if n.lower().endswith(".png")),
                       key=lambda n: (int(m.group()) if (m := re.match(r"\d+", n)) else 1 << 30, n))
        for n in names: items.append((app, tid, os.path.join(d, n)))

out = ["// Generated by tools/embed_presets.py - do not edit.",
       "#include <cstddef>", '#include "presets.h"']
for i, (_, _, path) in enumerate(items):
    data = open(path, "rb").read()
    out.append(f"static const unsigned char p{i}[] = {{")
    for j in range(0, len(data), 24):
        out.append("  " + ",".join(str(b) for b in data[j:j + 24]) + ",")
    out.append("};")
out.append("extern const Preset PRESETS[] = {")
for i, (app, tid, _) in enumerate(items):
    out.append(f'  {{"{app}", "{tid}", p{i}, sizeof p{i}}},')
out.append("};")
out.append(f"extern const size_t PRESETS_COUNT = {len(items)};")
open("src/presets_embed.cpp", "w").write("\n".join(out) + "\n")
print(f"wrote src/presets_embed.cpp ({len(items)} icons)")
