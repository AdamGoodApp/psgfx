import os
import sys

src, dst = sys.argv[1], sys.argv[2]
sys.path.insert(0, src)
from ps5at9 import atrac9_tables as T  # noqa: E402

LICENSE = open(os.path.join(src, "third_party", "LibAtrac9.LICENSE.txt")).read().strip()
HEAD = """// ATRAC9 constant tables, converted from LibAtrac9
// (https://github.com/Thealexbarney/LibAtrac9) via ps5at9/atrac9_tables.py of
// PS5 AT9 Converter. Generated by tools/at9check/gen_tables.py; do not edit.
//
// SPDX-License-Identifier: MIT
//
""" + "\n".join(("// " + l).rstrip() for l in LICENSE.splitlines()) + "\n"


def ints(v, per=20):
    v = list(v)
    rows = [", ".join(str(x) for x in v[i:i + per]) for i in range(0, len(v), per)]
    return "{\n    " + ",\n    ".join(rows) + "\n}" if v else "{0}"


def dbls(v):
    return "{" + ", ".join(repr(float(x)) for x in v) + "}"


maxcode = max(max(c) for b, c in list(T.SF_UNSIGNED.values()) + list(T.SF_SIGNED.values()))
maxcode = max(maxcode, max(max(c) for _p, _b, c in T.SPECTRUM.values()))
assert maxcode < 65536

h = [HEAD, "#pragma once", "#include <cstdint>", "", "namespace at9 {", "namespace tables {", "",
     "struct Huff { int size; int value_count_power; const uint8_t *bits; const uint16_t *codes; };", "",
     "// Scale factor codebooks indexed by word length (unsigned 1..6, signed 2..5); size 0 = absent.",
     "extern const Huff SF_UNSIGNED[7];", "extern const Huff SF_SIGNED[6];",
     "// Spectrum codebooks [codebook set][word length 0..7][codebook index]; size 0 = absent.",
     "extern const Huff SPECTRUM[2][8][4];",
     "extern const int SF_WEIGHTS[8][32];",
     "extern const int GRADIENT_MAIN[%d];" % len(T.GRADIENT_MAIN),
     "// Band extension tables (decoder only).",
     "extern const int BEX_GROUP_INFO[8][3];", "extern const int BEX_VALUE_COUNTS[5][6];",
     "extern const int BEX_DATA_LENGTHS[5][6][4];",
     "extern const double BEX_MODE0_BANDS3[5][32];", "extern const double BEX_MODE0_BANDS4[5][16];",
     "extern const double BEX_MODE0_BANDS5[3][32];",
     "extern const double BEX_MODE2_SCALE[%d];" % len(T.BEX_MODE2_SCALE),
     "extern const double BEX_MODE3_INITIAL[%d];" % len(T.BEX_MODE3_INITIAL),
     "extern const double BEX_MODE3_RATE[%d];" % len(T.BEX_MODE3_RATE),
     "extern const double BEX_MODE4_MULTIPLIER[%d];" % len(T.BEX_MODE4_MULTIPLIER),
     "", "} // namespace tables", "} // namespace at9", ""]

c = [HEAD, '#include "at9_tables.h"', "", "namespace at9 {", "namespace tables {", ""]


def book(name, bits, codes, vcp):
    c.append("static const uint8_t %s_bits[] = %s;" % (name, ints(bits)))
    c.append("static const uint16_t %s_codes[] = %s;" % (name, ints(codes)))
    return "{%d, %d, %s_bits, %s_codes}" % (len(bits), vcp, name, name)


refs = {}
for n, (b, cc) in sorted(T.SF_UNSIGNED.items()):
    refs[n] = book("sfu%d" % n, b, cc, 0)
c.append("const Huff SF_UNSIGNED[7] = {{0, 0, nullptr, nullptr}, %s};" %
         ", ".join(refs.get(n, "{0, 0, nullptr, nullptr}") for n in range(1, 7)))
refs = {}
for n, (b, cc) in sorted(T.SF_SIGNED.items()):
    refs[n] = book("sfs%d" % n, b, cc, 0)
c.append("const Huff SF_SIGNED[6] = {%s};" % ", ".join(refs.get(n, "{0, 0, nullptr, nullptr}") for n in range(6)))
refs = {}
for (s, w, ci), (p, b, cc) in sorted(T.SPECTRUM.items()):
    refs[(s, w, ci)] = book("sp%d_%d_%d" % (s, w, ci), b, cc, p)
rows = []
for s in range(2):
    ws = []
    for w in range(8):
        ws.append("{" + ", ".join(refs.get((s, w, ci), "{0, 0, nullptr, nullptr}") for ci in range(4)) + "}")
    rows.append("{" + ",\n  ".join(ws) + "}")
c.append("const Huff SPECTRUM[2][8][4] = {\n " + ",\n ".join(rows) + "};")
c.append("const int SF_WEIGHTS[8][32] = {%s};" % ",\n    ".join(ints(r, 32) for r in T.SF_WEIGHTS))
c.append("const int GRADIENT_MAIN[%d] = %s;" % (len(T.GRADIENT_MAIN), ints(T.GRADIENT_MAIN, 48)))
c.append("const int BEX_GROUP_INFO[8][3] = {%s};" % ", ".join(ints(r) for r in T.BEX_GROUP_INFO))
c.append("const int BEX_VALUE_COUNTS[5][6] = {%s};" % ", ".join(ints(r) for r in T.BEX_VALUE_COUNTS))
c.append("const int BEX_DATA_LENGTHS[5][6][4] = {%s};" %
         ", ".join("{" + ", ".join(ints(x) for x in r) + "}" for r in T.BEX_DATA_LENGTHS))
for name, rows_, w in (("BEX_MODE0_BANDS3", T.BEX_MODE0_BANDS3, 32), ("BEX_MODE0_BANDS4", T.BEX_MODE0_BANDS4, 16),
                       ("BEX_MODE0_BANDS5", T.BEX_MODE0_BANDS5, 32)):
    c.append("const double %s[%d][%d] = {%s};" % (name, len(rows_), w, ",\n    ".join(dbls(r) for r in rows_)))
for name in ("BEX_MODE2_SCALE", "BEX_MODE3_INITIAL", "BEX_MODE3_RATE", "BEX_MODE4_MULTIPLIER"):
    v = getattr(T, name)
    c.append("const double %s[%d] = %s;" % (name, len(v), dbls(v)))
c += ["", "} // namespace tables", "} // namespace at9", ""]

with open(os.path.join(dst, "at9_tables.h"), "w") as f:
    f.write("\n".join(h))
with open(os.path.join(dst, "at9_tables.cpp"), "w") as f:
    f.write("\n".join(c))
